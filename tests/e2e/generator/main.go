// Command generator aggregates every *_test_summary.md file under tests/e2e
// into a single tests/e2e/test-summary.md, grouped by the directory each
// summary came from. It is invoked via `go generate` from tests/e2e.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	summarySuffix = "_test_summary.md"
	outputFile    = "test-summary.md"
)

var skipDirs = map[string]bool{
	".git":      true,
	"bin":       true,
	"generator": true,
}

var headingRe = regexp.MustCompile(`^#{1,6} `)

var slugRe = regexp.MustCompile(`[^a-z0-9-]+`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "generate test summary:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}

	byDir, err := findSummaries(root)
	if err != nil {
		return err
	}
	if len(byDir) == 0 {
		return fmt.Errorf("no %s files found under %s", summarySuffix, root)
	}

	dirs := make([]string, 0, len(byDir))
	for dir := range byDir {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)

	var b strings.Builder
	b.WriteString("<!-- Code generated by go generate; DO NOT EDIT. -->\n")
	b.WriteString("# tests/e2e Test Summary\n\n")
	b.WriteString("Aggregated summaries of every e2e test suite, grouped by the package/directory each suite lives in.\n")
	b.WriteString("Generated from the `*_test_summary.md` files next to each test file — edit those, then run `go generate ./tests/e2e` to refresh this file.\n\n")

	b.WriteString("## Contents\n\n")
	for _, dir := range dirs {
		fmt.Fprintf(&b, "- [%s/](#%s)\n", dir, slug(dir))
	}
	b.WriteString("\n")

	for _, dir := range dirs {
		fmt.Fprintf(&b, "## %s/\n\n", dir)
		files := byDir[dir]
		sort.Strings(files)
		for _, f := range files {
			content, err := os.ReadFile(f)
			if err != nil {
				return err
			}
			b.WriteString(bumpHeadings(string(content)))
			b.WriteString("\n")
		}
	}

	return os.WriteFile(filepath.Join(root, outputFile), []byte(b.String()), 0o644)
}

// findSummaries walks root and returns every *_test_summary.md file found,
// keyed by its directory relative to root.
func findSummaries(root string) (map[string][]string, error) {
	byDir := make(map[string][]string)
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			name := d.Name()
			if path != root && (skipDirs[name] || strings.HasPrefix(name, ".")) {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(d.Name(), summarySuffix) {
			return nil
		}
		rel, err := filepath.Rel(root, filepath.Dir(path))
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		byDir[rel] = append(byDir[rel], path)
		return nil
	})
	return byDir, err
}

// bumpHeadings shifts every Markdown heading in content two levels deeper, so
// a summary file's own H1/H2 structure nests under this document's H1 title
// and per-directory H2 sections.
func bumpHeadings(content string) string {
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		if headingRe.MatchString(line) {
			lines[i] = "##" + line
		}
	}
	return strings.Join(lines, "\n")
}

// slug mirrors GitHub's Markdown anchor generation closely enough for the
// simple directory names used here (lowercase, non [a-z0-9-] runs collapsed
// to a single hyphen, trimmed).
func slug(s string) string {
	s = strings.ToLower(s)
	s = slugRe.ReplaceAllString(s, "-")
	return strings.Trim(s, "-")
}
