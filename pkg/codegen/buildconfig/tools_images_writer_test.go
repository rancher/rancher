package main

import (
	"bytes"
	"errors"
	"go/parser"
	"go/token"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const wantToolsSystemImages = `// Code generated by pkg/codegen/buildconfig/main.go. DO NOT EDIT.

package v3

var (
	// ToolsSystemImages holds the default system images used by Rancher.
	//
	// Deprecated: use buildconfig.DefaultKubeApiAuthImage from
	// github.com/rancher/rancher/pkg/buildconfig instead. This var will be removed in a
	// future release.
	ToolsSystemImages = struct {
		AuthSystemImages AuthSystemImages
	}{
		AuthSystemImages: AuthSystemImages{
			KubeAPIAuth: "rancher/kube-api-auth:v0.16.0-rc.3",
		},
	}
)
`

func TestToolsSystemImagesWriterRun(t *testing.T) {
	t.Parallel()

	out := new(bytes.Buffer)
	w := ToolsSystemImagesWriter{
		Config: map[string]string{
			"defaultKubeApiAuthImage": "rancher/kube-api-auth:v0.16.0-rc.3",
			"defaultShellVersion":     "rancher/shell:v0.9.0",
		},
		Output: out,
	}
	require.NoError(t, w.Run())
	assert.Equal(t, wantToolsSystemImages, out.String())

	// The output must be a valid Go file in the v3 package.
	f, err := parser.ParseFile(token.NewFileSet(), "tools_system_images.go", out.Bytes(), parser.AllErrors)
	require.NoError(t, err)
	assert.Equal(t, "v3", f.Name.Name)
}

func TestToolsSystemImagesWriterRunIsIdempotent(t *testing.T) {
	t.Parallel()

	cfg := map[string]string{"defaultKubeApiAuthImage": "rancher/kube-api-auth:v1.2.3"}
	first, second := new(bytes.Buffer), new(bytes.Buffer)
	require.NoError(t, (&ToolsSystemImagesWriter{Config: cfg, Output: first}).Run())
	require.NoError(t, (&ToolsSystemImagesWriter{Config: cfg, Output: second}).Run())
	assert.Equal(t, first.String(), second.String())
}

func TestToolsSystemImagesWriterRunEscapesValue(t *testing.T) {
	t.Parallel()

	out := new(bytes.Buffer)
	w := ToolsSystemImagesWriter{
		Config: map[string]string{"defaultKubeApiAuthImage": `weird"image\tag`},
		Output: out,
	}
	require.NoError(t, w.Run())
	assert.Contains(t, out.String(), `KubeAPIAuth: "weird\"image\\tag",`)

	_, err := parser.ParseFile(token.NewFileSet(), "tools_system_images.go", out.Bytes(), parser.AllErrors)
	require.NoError(t, err, "escaped value must still produce valid Go")
}

func TestToolsSystemImagesWriterRunErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		config  map[string]string
		output  *bytes.Buffer
		wantErr string
	}{
		{
			name:    "nil config",
			config:  nil,
			output:  new(bytes.Buffer),
			wantErr: "nil config",
		},
		{
			name:    "nil output",
			config:  map[string]string{"defaultKubeApiAuthImage": "rancher/kube-api-auth:v1"},
			output:  nil,
			wantErr: "nil output",
		},
		{
			name:    "missing key",
			config:  map[string]string{"defaultShellVersion": "rancher/shell:v0.9.0"},
			output:  new(bytes.Buffer),
			wantErr: "defaultKubeApiAuthImage",
		},
		{
			name:    "empty value",
			config:  map[string]string{"defaultKubeApiAuthImage": ""},
			output:  new(bytes.Buffer),
			wantErr: "missing or empty",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			w := ToolsSystemImagesWriter{Config: tt.config}
			if tt.output != nil {
				w.Output = tt.output
			}
			require.ErrorContains(t, w.Run(), tt.wantErr)
			if tt.output != nil {
				assert.Zero(t, tt.output.Len(), "nothing should be written on error")
			}
		})
	}
}

type failingWriter struct{}

func (failingWriter) Write([]byte) (int, error) { return 0, errors.New("disk full") }

func TestToolsSystemImagesWriterRunOutputError(t *testing.T) {
	t.Parallel()

	w := ToolsSystemImagesWriter{
		Config: map[string]string{"defaultKubeApiAuthImage": "rancher/kube-api-auth:v1"},
		Output: failingWriter{},
	}
	require.ErrorContains(t, w.Run(), "disk full")
}
